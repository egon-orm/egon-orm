/**
 * What a changeset knows about the fields it works on, computed once per schema class
 * (or per `types` object of a changeset without one) and shared by every changeset of it.
 *
 * @module
 */
import type { AnySchema, FieldMeta, SchemaMeta } from "../contracts/schema.js";
import { CastError, QueryError } from "../errors.js";
import { own } from "../internal/own.js";
import { isPlainObject } from "../internal/plain-object.js";
import { fieldState, isRow, isSchema, meta } from "../schema/index.js";
import { refuseGeneration } from "./validators/generated.js";

/** The fields of a changeset's target and what is derived from them. */
export interface Spec {
  /** The class name, or `"schemaless"`, for messages and inspect output. */
  readonly name: string;
  readonly model: AnySchema | null;
  /** The schema metadata; `null` without a schema class. */
  readonly meta: SchemaMeta | null;
  readonly fields: ReadonlyMap<string, FieldMeta>;
  readonly redacted: ReadonlySet<string>;
  /** What `validateRequired()` checks with no list: non-nullable stored fields that nothing else fills. */
  readonly requiredByDefault: readonly string[];
  /** Embed fields: not cast by `cast`. */
  readonly embeds: ReadonlySet<string>;
}

const bySchema = /* @__PURE__ */ new WeakMap<SchemaMeta, Spec>();
const byTypes = /* @__PURE__ */ new WeakMap<object, Spec>();

function requiredByDefault(fields: readonly FieldMeta[]): readonly string[] {
  return Object.freeze(
    fields
      .filter(
        (field) =>
          !field.nullable &&
          !field.virtual &&
          field.default === undefined &&
          field.autogenerate === undefined &&
          !field.dbGenerated,
      )
      .map((field) => field.name),
  );
}

/** The spec of a schema class. */
export function specOfSchema(schema: AnySchema): Spec {
  const schemaMeta = meta(schema);
  let spec = bySchema.get(schemaMeta);
  if (spec === undefined) {
    spec = Object.freeze({
      name: schemaMeta.name,
      model: schema,
      meta: schemaMeta,
      fields: schemaMeta.fieldsByName,
      redacted: new Set(schemaMeta.fields.filter((field) => field.redact).map((field) => field.name)),
      requiredByDefault: requiredByDefault(schemaMeta.fields),
      embeds: new Set(schemaMeta.embeds.map((embed) => embed.name)),
    });
    bySchema.set(schemaMeta, spec);
  }
  return spec;
}

/** The spec of the `types` of a changeset without a schema class. */
function specOfTypes(types: unknown): Spec {
  if (typeof types !== "object" || types === null || !isPlainObject(types)) {
    throw new QueryError(
      "query.schemalessShape",
      "A changeset without a schema class needs { data, types }, where types is an object from field name to type.",
    );
  }
  let spec = byTypes.get(types);
  if (spec !== undefined) return spec;
  const fields: FieldMeta[] = [];
  const embeds = new Set<string>();
  for (const name of Object.keys(types)) {
    const state = fieldState((types as Readonly<Record<string, unknown>>)[name]);
    if (state === undefined) {
      throw new QueryError(
        "query.schemalessFieldType",
        `The type of the field "${name}" is not a field type.`,
        { params: { name } },
      );
    }
    if (name === "__proto__" || name === "constructor") {
      throw new QueryError("query.schemalessFieldName", `"${name}" cannot be the name of a field.`);
    }
    if (state.autogenerate !== undefined || state.dbGenerated) {
      throw new QueryError(
        "query.schemalessGenerated",
        `The field "${name}" is ${state.dbGenerated ? "database-generated" : "autogenerated"}, which means nothing without a table.`,
      );
    }
    if (state.embed !== undefined) embeds.add(name);
    fields.push(
      Object.freeze({
        name,
        column: state.column ?? name,
        type: state.type,
        nullable: state.nullable,
        primaryKey: state.primaryKey,
        virtual: state.virtual,
        redact: state.redact,
        json: state.json,
        writable: state.writable,
        dbGenerated: state.dbGenerated,
        default: state.default,
        autogenerate: state.autogenerate,
        index: fields.length,
      }),
    );
  }
  const byName: ReadonlyMap<string, FieldMeta> = new Map(fields.map((field) => [field.name, field]));
  // A changeset without a schema class never generates code: there is no `codegen` option
  // to turn it off, and a strict Content Security Policy would report the attempt. Its
  // validator builders are loops.
  refuseGeneration(byName);
  spec = Object.freeze({
    name: "schemaless",
    model: null,
    meta: null,
    fields: byName,
    redacted: new Set(fields.filter((field) => field.redact).map((field) => field.name)),
    requiredByDefault: requiredByDefault(fields),
    embeds,
  });
  byTypes.set(types, spec);
  return spec;
}

/** The schema class of a row, or `undefined` when `value` is not a row. */
function classOfRow(value: object): AnySchema | undefined {
  if (!isRow(value)) return undefined;
  const prototype: unknown = Object.getPrototypeOf(value);
  const ctor: unknown =
    typeof prototype === "object" && prototype !== null
      ? (prototype as { readonly constructor?: unknown }).constructor
      : undefined;
  return isSchema(ctor) ? ctor : undefined;
}

/** What `cast` and `change` start from, when the target is not a changeset. */
export interface Start {
  readonly spec: Spec;
  readonly data: object | null;
}

/**
 * Reads a target that is a schema class, a row or `{ data, types }`.
 *
 * @throws QueryError when `target` is none of these.
 */
export function startOf(target: unknown, fn: "cast" | "change"): Start {
  if (isSchema(target)) return { spec: specOfSchema(target), data: null };
  if (typeof target === "object" && target !== null) {
    const model = classOfRow(target);
    if (model !== undefined) return { spec: specOfSchema(model), data: target };
    if (isPlainObject(target) && Object.hasOwn(target, "types")) {
      const { types } = target as { readonly types: unknown };
      const data = own(target as { readonly data?: unknown }, "data");
      const spec = specOfTypes(types);
      if (typeof data !== "object" || data === null || !isPlainObject(data)) {
        throw new QueryError(
          "query.schemalessData",
          `${fn}({ data, types }): data must be a plain object holding the current values.`,
        );
      }
      return { spec, data };
    }
  }
  throw new QueryError(
    "query.changesetSource",
    `${fn}() takes a schema class (for a new record), a row (for an update), a changeset, or { data, types } for a changeset without a schema class.`,
  );
}

/**
 * Checks the params given to `cast`: a plain object, or `null`/`undefined` for none.
 *
 * @throws CastError for anything else.
 */
export function paramsOf(params: unknown): Readonly<Record<string, unknown>> | undefined {
  if (params === null || params === undefined) return undefined;
  if (typeof params === "object" && !Array.isArray(params) && isPlainObject(params)) {
    return params as Readonly<Record<string, unknown>>;
  }
  const kind = Array.isArray(params)
    ? "an array"
    : typeof params === "object"
      ? "an object that is not plain"
      : `a ${typeof params}`;
  throw new CastError(
    "cast.paramsNotObject",
    `cast() expects params to be a plain object (or null or undefined for none), but got ${kind}.`,
  );
}

/** The field named `name`, or a `QueryError` saying what is wrong. */
export function fieldOf(spec: Spec, name: unknown, fn: string): FieldMeta {
  const field = typeof name === "string" ? spec.fields.get(name) : undefined;
  if (field !== undefined) return field;
  if (typeof name !== "string") {
    throw new QueryError("query.fieldNameType", `${fn}() takes a field name as a string.`);
  }
  if (spec.meta?.assocs().has(name)) {
    throw new QueryError(
      "query.fieldIsAssoc",
      `${fn}(): "${name}" is an association of ${spec.name}, not a field.`,
    );
  }
  throw new QueryError(
    "query.changesetFieldUnknown",
    `${fn}(): ${spec.name} has no field "${name}". Its fields are: ${[...spec.fields.keys()].join(", ")}.`,
  );
}
